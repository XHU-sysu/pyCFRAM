def test_full_variable_ipsl_all_active_and_no_nan():
    cfg = _base_cfg(IPSL_RAW_DIR, 'IPSL-CM6A-LR', grid_label='gr')
    src = damip.CMIP6DamipSource(cfg)
    base, warm, nonrad = src.build_states()

    _assert_no_nan(base, 'base')
    _assert_no_nan(warm, 'warm')

    proc = src.provenance['processes']
    assert proc['cloud']['status'] == 'ACTIVE'
    assert proc['o3']['status'] == 'MODEL'
    assert proc['solar']['status'] == 'ACTIVE'
    assert proc['flux']['status'] == 'ACTIVE'
    assert proc['albedo']['status'] == 'ACTIVE'
    assert proc['aerosol']['status'] == 'SKIPPED'

    # camt physically bounded
    assert base['camt'].min() >= 0.0 and base['camt'].max() <= 1.0
    assert warm['camt'].min() >= 0.0 and warm['camt'].max() <= 1.0


def test_full_variable_ipsl_exact_deltas():
    """ta/ts/rsdt/hfls/hfss/o3 all use per-year-constant fixture values with
    base_years=[1850,1851] / warm_years=[1854,1855] both non-leap pairs
    (gregorian) -> warm_mean - base_mean is an EXACT linear-trend multiple
    (4.0x the per-year trend), not just approximately equal (see
    _make_damip_fixtures.py's module docstring)."""
    cfg = _base_cfg(IPSL_RAW_DIR, 'IPSL-CM6A-LR', grid_label='gr')
    src = damip.CMIP6DamipSource(cfg)
    base, warm, nonrad = src.build_states()

    # ta trend = +0.6 K/yr, ts trend = +0.6 K/yr (same rate) -> +2.4 K
    # uniformly everywhere, INCLUDING the mountain column's HOLD/ts-filled
    # subsurface cells (ta_lay there == ts, which shifts by the same 2.4 K).
    dT = warm['ta_lay'] - base['ta_lay']
    np.testing.assert_allclose(dT, 2.4, atol=1e-8)

    # rsdt/o3 are time-invariant in the fixture -> exactly zero delta
    # (hist-aer freezes solar + this model's O3 pipeline uses the SAME
    # constant field for both periods).
    np.testing.assert_allclose(warm['solar'] - base['solar'], 0.0, atol=1e-10)
    np.testing.assert_allclose(warm['o3'] - base['o3'], 0.0, atol=1e-10)

    # albedo: rsus/rsds both time-invariant -> identical base/warm, = 40/200
    np.testing.assert_allclose(base['albedo'], 0.2, atol=1e-10)
    np.testing.assert_allclose(warm['albedo'], 0.2, atol=1e-10)

    # hfls trend +5 W/m2/yr, hfss trend +2 W/m2/yr -> Delta = 4.0x trend;
    # frc = -(warm-base) (docs/plan_ph3.md §2.5 sign law).
    np.testing.assert_allclose(nonrad['lhflx'], -20.0, atol=1e-8)
    np.testing.assert_allclose(nonrad['shflx'], -8.0, atol=1e-8)

    # cloud: aerosol-driven decline (-1%/yr trend in cl) -> warm domain mean
    # cloud fraction is lower than base (qualitative -- hybrid mass-conserving
    # projection + the mountain column's partial-layer truncation make an
    # exact closed form impractical to hand-verify here).
    assert warm['camt'].mean() < base['camt'].mean()


