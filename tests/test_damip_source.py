# Differing target grid -> genuine (non-identity) interp_plev_to_target path
# ---------------------------------------------------------------------------

def test_differing_target_grid_interpolates_without_crashing():
    # Extra level (600 hPa) not present in the native fixture plev -- forces
    # a real (non-identity) log-p interpolation for ta/hus/o3, and a
    # differently-shaped mass-conserving hybrid projection for cl/clw/cli.
    target = [100.0, 300.0, 500.0, 600.0, 700.0, 1000.0]
    cfg = _base_cfg(IPSL_RAW_DIR, 'IPSL-CM6A-LR', grid_label='gr', target_plev=target)
    src = damip.CMIP6DamipSource(cfg)
    base, warm, _ = src.build_states()

    _assert_no_nan(base, 'base')
    _assert_no_nan(warm, 'warm')
    assert base['ta_lay'].shape[0] == len(target)
    assert base['lev'].tolist() == list(reversed(target))

    # Interpolated 600 hPa level (index 3 in sfc->TOA order, between the
    # native 500 and 700 hPa levels) must lie between the two neighboring
    # native temperatures at a non-mountain column (log-p linear interp of a
    # monotone profile stays monotone-bounded).
    lev_sfc2toa = base['lev']
    i600 = list(lev_sfc2toa).index(600.0)
    i500 = list(lev_sfc2toa).index(500.0)
    i700 = list(lev_sfc2toa).index(700.0)
    non_mountain = (1, 1)   # away from the (0,0) mountain column
    t600 = base['ta_lay'][i600][non_mountain]
    t500 = base['ta_lay'][i500][non_mountain]
    t700 = base['ta_lay'][i700][non_mountain]
    assert min(t500, t700) <= t600 <= max(t500, t700)


# ---------------------------------------------------------------------------
# hybrid_ab_p0 (CESM2-style) coefficient reading -- not exercised by
# build_states() integration tests above, because CESM2's real hist-aer
# publication has no cl/clw/cli at all (docs/plan_ph3.md §1.4), so cloud
# processing never reaches vertical-coordinate detection for that model in
# practice. Unit-test _read_hybrid_coeffs directly against a small
# CESM2-style (scalar p0 variable) fixture instead.
# ---------------------------------------------------------------------------

def test_read_hybrid_coeffs_ab_p0_convention(tmp_path):
    path = str(tmp_path / 'cl_hybrid_ab_p0.nc')
    with Dataset(path, 'w') as nc:
        nc.createDimension('lev', 3)
        lv = nc.createVariable('lev', 'f8', ('lev',))
        lv[:] = [1, 2, 3]
        lv.standard_name = 'atmosphere_hybrid_sigma_pressure_coordinate'
        lv.formula_terms = 'p0: p0 a: a b: b ps: ps'
        p0v = nc.createVariable('p0', 'f8', ())
        p0v[...] = 100000.0
        nc.createVariable('a', 'f8', ('lev',))[:] = [0.01, 0.02, 0.0]
        nc.createVariable('b', 'f8', ('lev',))[:] = [0.0, 0.3, 0.98]
        cl = nc.createVariable('cl', 'f8', ('lev',))
        cl.formula_terms = 'p0: p0 a: a b: b ps: ps'
        cl[:] = [1.0, 20.0, 40.0]

    with Dataset(path) as nc:
        formula_terms = nc.variables['cl'].formula_terms
        from data import cmip6_common as common
        vinfo = common.detect_vertical(formula_terms=formula_terms)
        assert vinfo['scheme'] == 'hybrid_ab_p0'
        a_eff, b_eff, p0_eff = damip._read_hybrid_coeffs(nc, vinfo)
        np.testing.assert_array_equal(a_eff, [0.01, 0.02, 0.0])
        np.testing.assert_array_equal(b_eff, [0.0, 0.3, 0.98])
        assert p0_eff == 100000.0

        # Feed straight into hybrid_to_plev_mass_conserving to confirm the
        # coefficients actually work end-to-end for a real (non-mocked) file.
        ps_2d = np.array([[101300.0]])
        field_hyb = np.array([1.0, 20.0, 40.0]).reshape(3, 1, 1)
        target_toa2sfc_pa = np.array([50000.0, 101300.0])
        out = common.hybrid_to_plev_mass_conserving(field_hyb, a_eff, b_eff, p0_eff, ps_2d,
                                                     target_toa2sfc_pa)
        assert out.shape == (2, 1, 1)
        assert np.all(np.isfinite(out))
