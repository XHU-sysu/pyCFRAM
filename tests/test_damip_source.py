def test_missing_cloud_rsdt_o3_cesm2_climatology():
    cfg = _base_cfg(CESM2_RAW_DIR, 'CESM2', grid_label='gn', o3='auto',
                    o3_climatology_path=O3_CLIMO_MINI)
    src = damip.CMIP6DamipSource(cfg)
    base, warm, nonrad = src.build_states()

    _assert_no_nan(base, 'base')
    _assert_no_nan(warm, 'warm')

    proc = src.provenance['processes']
    assert proc['cloud']['status'] == 'SKIPPED'
    assert proc['solar']['status'] == 'ANALYTIC'
    assert proc['o3']['status'] == 'CLIMATOLOGY'

    # cloud=SKIPPED -> exactly zero, both states
    for v in ('camt', 'cliq', 'cice'):
        assert np.all(base[v] == 0.0)
        assert np.all(warm[v] == 0.0)

    # solar=ANALYTIC: same lat-only function for both states -> bit-identical
    np.testing.assert_array_equal(base['solar'], warm['solar'])
    # anchors: analytic_solar output should be within a physically sane W/m2 range
    assert 0.0 < base['solar'].min()
    assert base['solar'].max() < 500.0

    # o3=CLIMATOLOGY: same injected field for both states -> bit-identical,
    # and in a physically sane kg/kg range for the mini climatology (mol/mol
    # 3e-8..5e-6 x 48/29).
    np.testing.assert_array_equal(base['o3'], warm['o3'])
    assert base['o3'].min() > 1e-9
    assert base['o3'].max() < 1e-4


def test_o3_climatology_source_missing_falls_back_to_skip_constant(monkeypatch):
    """o3=auto, no model o3, AND no climatology source resolvable at all
    (monkeypatch the module's candidate-path tuple to something that can't
    exist) -> constant 1e-12 kg/kg fallback, status SKIPPED. Guards against
    the real raw_data/ozone_*.nc file (which genuinely exists in this repo)
    accidentally satisfying the injection path in this specific test."""
    monkeypatch.setattr(damip, '_O3_CLIMATOLOGY_CANDIDATES', ('does/not/exist.nc',))
    cfg = _base_cfg(CESM2_RAW_DIR, 'CESM2', grid_label='gn', o3='auto')
    src = damip.CMIP6DamipSource(cfg)
    base, warm, _ = src.build_states()

    assert src.provenance['processes']['o3']['status'] == 'SKIPPED'
    np.testing.assert_array_equal(base['o3'], damip.O3_SKIP_CONSTANT_KGKG)
    np.testing.assert_array_equal(warm['o3'], damip.O3_SKIP_CONSTANT_KGKG)


